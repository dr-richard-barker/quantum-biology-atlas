// drawing
// ---------------------------------------------------------------------------

function divergingFill(value, vmax) {
  if (!(vmax > 0)) return 'rgba(0,0,0,0)';
  const t = Math.max(-1, Math.min(1, value / vmax));
  const [r, g, b] = t >= 0 ? UP : DOWN;
  return `rgba(${r},${g},${b},${(Math.abs(t) * MAX_ALPHA).toFixed(3)})`;
}

function applyOverlay(svgRoot, values, vmax) {
  // Clear any previous run first, or a second upload inherits the first one's colours.
  svgRoot.querySelectorAll('[data-overlay-for]').forEach((el) => { el.style.fill = 'none'; });
  svgRoot.querySelectorAll('.qbm-user-value').forEach((el) => el.remove());

  let tinted = 0;
  for (const [nodeId, v] of Object.entries(values)) {
    const slot = svgRoot.querySelector(`[data-overlay-for="${CSS.escape(nodeId)}"]`);
    if (!slot) continue;
    slot.style.fill = divergingFill(v.value, vmax);
    tinted++;

    const rect = svgRoot.querySelector(`[data-node-rect="${CSS.escape(nodeId)}"]`);
    if (!rect) continue;
    const x = parseFloat(rect.getAttribute('x'));
    const y = parseFloat(rect.getAttribute('y'));
    const w = parseFloat(rect.getAttribute('width'));
    const h = parseFloat(rect.getAttribute('height'));
    const txt = `${v.value >= 0 ? '+' : ''}${v.value.toFixed(2)}${v.significant ? '*' : ''}`;
    const g = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    g.setAttribute('class', 'qbm-user-value');
    g.setAttribute('data-value-for', nodeId);
    const bw = 8 + txt.length * 5.6;
    g.innerHTML =
      `<rect class="qbm-unit" x="${(x + w - bw / 2).toFixed(2)}" y="${(y + h - 7).toFixed(2)}" ` +
      `width="${bw.toFixed(2)}" height="14" rx="7"></rect>` +
      `<text class="qbm-unit-label" x="${(x + w).toFixed(2)}" y="${(y + h + 3).toFixed(2)}" ` +
      `text-anchor="middle">${txt}</text>`;
    rect.parentNode.appendChild(g);
  }
  return tinted;
}

