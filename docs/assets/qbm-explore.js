/** Parse CSV or TSV. Delimiter is sniffed; quoted fields are handled. */
function parseTable(text) {
  const firstLine = text.slice(0, 8192).split('\n')[0] || '';
  const delim = (firstLine.match(/\t/g) || []).length > (firstLine.match(/,/g) || []).length ? '\t' : ',';
  const rows = [];
  let field = '', row = [], inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') { field += '"'; i++; } else inQuotes = false;
      } else field += c;
    } else if (c === '"') inQuotes = true;
    else if (c === delim) { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const clean = rows.filter((r) => r.some((c) => c.trim() !== ''));
  if (clean.length < 2) throw new Error('file has no data rows');
  const header = clean[0].map((h) => h.trim());
  return { header, rows: clean.slice(1), delimiter: delim === '\t' ? 'TSV' : 'CSV' };
}

/**
 * Pick the value column: prefer an explicit log2-fold-change name, otherwise the first
 * column that is mostly numeric. Named ahead of positional so a table with several
 * numeric columns does not silently pick the wrong one.
 */
function pickValueColumn(header, rows) {
  const named = header.findIndex((h) => /log2\s*fold|log2fc|log2_fc|logfc/i.test(h));
  if (named >= 0) return named;
  for (let c = 1; c < header.length; c++) {
    const vals = rows.slice(0, 200).map((r) => r[c]).filter((v) => v && v.trim() !== '');
    if (!vals.length) continue;
    const numeric = vals.filter((v) => Number.isFinite(Number(v))).length / vals.length;
    if (numeric > 0.8) return c;
  }
  throw new Error('no numeric value column found — expected a log2 fold change');
}

function pickIdColumn(header, rows) {
  let best = { index: 0, fraction: -1, ns: null };
  for (let c = 0; c < header.length; c++) {
    const vals = rows.slice(0, 400).map((r) => r[c]).filter(Boolean);
    const ns = detectNamespace(vals);
    if (ns.fraction > best.fraction) best = { index: c, fraction: ns.fraction, ns };
  }
  return best;
}

function pickPadjColumn(header) {
  const i = header.findIndex((h) => /^(adj\.?p|padj|adjusted|fdr|q[_.]?value)/i.test(h.trim()));
  return i >= 0 ? i : null;
}

