const AGGREGATORS = {
  mean: (v) => v.reduce((a, b) => a + b, 0) / v.length,
  median: (v) => { const s = [...v].sort((a, b) => a - b); const m = s.length >> 1;
    return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; },
  extreme: (v) => v.reduce((a, b) => (Math.abs(b) > Math.abs(a) ? b : a), 0),
};

/**
 * Join the parsed table onto the map's nodes.
 *
 * Returns per-node values plus a full coverage account: what matched, what did not, and
 * which loci had no counterpart in the target species. Nothing is dropped silently.
 */
function joinToMap(parsed, sidecar, orthologs, opts) {
  const { idIndex, valueIndex, padjIndex, species, aggregator, alpha } = opts;
  const combine = AGGREGATORS[aggregator] || AGGREGATORS.mean;

  // Build lookup: uploaded id -> value.
  const table = new Map();
  const padj = new Map();
  let unparseable = 0;
  for (const r of parsed.rows) {
    const id = (r[idIndex] || '').trim().toUpperCase().split('.')[0];
    const v = Number(r[valueIndex]);
    if (!id || !Number.isFinite(v)) { unparseable++; continue; }
    table.set(id, v);
    if (padjIndex != null) {
      const p = Number(r[padjIndex]);
      if (Number.isFinite(p)) padj.set(id, p);
    }
  }
  if (table.size === 0) throw new Error('no rows had both an identifier and a numeric value');

  // Arabidopsis locus -> ids to look for in the uploaded table.
  const sameSpecies = species === 'arabidopsis_thaliana';
  const speciesMap = sameSpecies ? null : (orthologs?.species?.[species]?.orthologs || {});

  const values = {};
  const withoutLoci = [];
  const unmatched = [];
  const noOrtholog = [];
  let matchedIds = new Set();

  for (const node of sidecar.nodes) {
    if (!node.agi || node.agi.length === 0) { withoutLoci.push(node.node_id); continue; }
    const hits = [];
    const used = [];
    const via = [];
    let anySig = null;
    let lostToOrthology = 0;

    for (const locus of node.agi) {
      const key = locus.toUpperCase();
      let queries;
      if (sameSpecies) queries = [key];
      else {
        const m = speciesMap[key];
        if (!m) { lostToOrthology++; continue; }
        queries = m.targets.map((t) => t.toUpperCase());
      }
      for (const q of queries) {
        if (!table.has(q)) continue;
        hits.push(table.get(q));
        used.push(locus);
        matchedIds.add(q);
        if (q !== key) via.push(`${locus}→${q}`);
        if (padj.has(q)) anySig = anySig || padj.get(q) <= alpha;
      }
    }
    if (hits.length === 0) {
      (lostToOrthology === node.agi.length && !sameSpecies ? noOrtholog : unmatched).push(node.node_id);
      continue;
    }
    values[node.node_id] = {
      value: combine(hits),
      n: hits.length,
      loci: [...new Set(used)],
      via,
      significant: anySig,
      tier: node.evidence_tier,
      label: node.label,
    };
  }

  const addressable = sidecar.nodes.length - withoutLoci.length;
  return {
    values,
    coverage: {
      nodesTotal: sidecar.nodes.length,
      nodesWithData: Object.keys(values).length,
      addressable,
      fraction: addressable ? Object.keys(values).length / addressable : 0,
      withoutLoci,
      unmatched,
      noOrtholog,
      rowsParsed: table.size,
      rowsUnparseable: unparseable,
      rowsUsed: matchedIds.size,
    },
  };
}

