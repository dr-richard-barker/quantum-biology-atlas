/**
 * Guess which identifier namespace a column of values is in.
 *
 * Detecting rather than asking avoids the commonest silent failure: a user uploads
 * Ensembl ids against an AGI-keyed map, everything misses, and a blank map is rendered.
 * Here a namespace that cannot reach the chosen species is an explicit error.
 */
const NAMESPACES = [
  { id: 'agi', label: 'Arabidopsis AGI locus', species: 'arabidopsis_thaliana', re: /^AT[1-5CM]G\d{5}$/i },
  { id: 'flybase', label: 'FlyBase gene', species: 'drosophila_melanogaster', re: /^FBgn\d{7}$/i },
  { id: 'ensembl', label: 'Ensembl gene', species: null, re: /^ENS[A-Z]*G\d{6,}$/i },
  { id: 'wormbase', label: 'WormBase gene', species: 'caenorhabditis_elegans', re: /^WBGene\d{8}$/i },
  { id: 'sgd', label: 'SGD systematic name', species: 'saccharomyces_cerevisiae', re: /^Y[A-P][LR]\d{3}[WC]/i },
];

function detectNamespace(values) {
  const sample = values.filter(Boolean).slice(0, 400);
  let best = { id: 'unknown', label: 'unrecognised', fraction: 0, species: null };
  for (const ns of NAMESPACES) {
    const hits = sample.filter((v) => ns.re.test(v.trim())).length;
    const fraction = sample.length ? hits / sample.length : 0;
    if (fraction > best.fraction) best = { ...ns, fraction };
  }
  return best;
}

