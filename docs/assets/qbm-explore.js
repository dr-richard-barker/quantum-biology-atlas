/**
 * qbm-explore — project your own expression data onto a quantum pathway map.
 *
 * Runs entirely in the browser. Nothing is uploaded anywhere: the file is read with
 * FileReader, joined against the catalogue, and drawn. That is a deliberate property,
 * not an accident of hosting — unpublished data should not have to leave the machine to
 * be looked at.
 *
 * The join is possible client-side because the build already emits everything needed:
 *   - each map SVG carries data-node-id / data-qbo / data-tier / data-overlay-for
 *   - catalog/qbo/QBM-*.json carries agi, evidence_tier, quantum_class and cited
 *     evidence per node
 *   - catalog/orthologs.json carries the Arabidopsis-to-model-species mapping, so a
 *     fly or human table can be joined without any network call
 *
 * The refusals are ported from qbio.project deliberately. A join that matches nothing,
 * rendered as a pale map, looks like a result — it is the worst failure available here,
 * worse than an error message. So an empty join refuses outright and a thin one warns
 * loudly with its coverage stated.
 */

const CATALOG = 'catalog';
const MAPS = 'maps/svg';

// Okabe-Ito, matching qbio.render.diverging_fill so an uploaded overlay looks identical
// to one generated by the Python pipeline. Blue = down, vermillion = up.
const DOWN = [0, 114, 178];
const UP = [213, 94, 0];
const MAX_ALPHA = 0.78;

/** Coverage below this is reported as a warning: the figure would mislead. */
const LOW_COVERAGE = 0.25;

const state = {
  manifest: null,
  orthologs: null,
  mapId: null,
  sidecar: null,
  rows: null,
  species: 'arabidopsis_thaliana',
  aggregator: 'mean',
  alpha: 0.05,
};

